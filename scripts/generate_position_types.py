"""Generate the positions TypeScript contract from FastAPI OpenAPI.
Run from backend with its environment: python ../scripts/generate_position_types.py.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from app.main import app  # noqa: E402

schema = app.openapi()
names = ['PositionRequest', 'Angles', 'PositionSample', 'PositionSource', 'VisibilitySummary', 'VisibilityEvent', 'VisibilityWindow', 'VisibilityResult', 'PositionResult', 'MissionSite', 'MissionPositionRequest', 'MissionPositionResult', 'Requirements', 'RequirementCheck', 'SiteProgress', 'MissionAnalysisRead', 'MissionAnalysisIndex', 'AccountRead']


def ts(value):
    if 'enum' in value:
        return ' | '.join(json.dumps(item) for item in value['enum'])
    if 'anyOf' in value:
        return ' | '.join(ts(item) for item in value['anyOf'])
    if '$ref' in value:
        return value['$ref'].rsplit('/', 1)[1]
    kind = value.get('type')
    if kind == 'array':
        return f"({ts(value['items'])})[]"
    if kind == 'object':
        return f"Record<string, {ts(value['additionalProperties'])}>"
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'null': 'null', 'boolean': 'boolean'}[kind]


output = '// Generated by scripts/generate_position_types.py; do not edit.\n'
for name in names:
    model = schema['components']['schemas'][name]
    output += f'export interface {name} {{\n'
    for field, value in model['properties'].items():
        optional = '' if field in model.get('required', []) else '?'
        output += f'  {field}{optional}: {ts(value)};\n'
    output += '}\n'
(ROOT / 'frontend/src/services/position-contract.ts').write_text(output)
(ROOT / 'docs/sources/positions-openapi.json').write_text(json.dumps({
    'openapi': schema['openapi'], 'info': schema['info'],
    'paths': {'/api/positions': schema['paths']['/api/positions']},
    'components': schema['components'],
}, indent=2) + '\n')

(ROOT / 'docs/sources/mission-openapi.json').write_text(json.dumps({
    'openapi': schema['openapi'], 'info': schema['info'],
    'paths': {path: value for path, value in schema['paths'].items() if path.startswith(('/api/auth', '/api/mission'))},
    'components': schema['components'],
}, indent=2) + '\n')
